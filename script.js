function createEditionBadge(edition) {
    const isPaper = edition.toLowerCase() === "paper";
    const badgeClass = isPaper ? "badge-paper" : "badge-fabric";
    const icon = isPaper ? ICONS.paper : ICONS.fabric;
    return `<span class="badge ${badgeClass}">${icon}<span>${edition}</span></span>`;
}

const grid = document.getElementById("projects-grid");

async function loadProjects() {
    const response = await fetch('projects.json?v=1');
    const projects = await response.json();
    console.log(projects)
    
    grid.innerHTML = projects
        .map(
            (project) => `
            <article class="card">
                <div class="card-header">
                    <h2 class="card-title">${project.name}</h2>
                    ${createEditionBadge(project.edition)}
                </div>
                <p class="card-desc">${project.description}</p>
                <div class="card-links">
                    <a class="btn btn-modrinth" href="${project.links.modrinth}" target="_blank" rel="noopener noreferrer">
                        ${ICONS.modrinth}<span>Modrinth</span>
                    </a>
                    <a class="btn btn-curseforge" href="${project.links.curseforge}" target="_blank" rel="noopener noreferrer">
                        ${ICONS.curseforge}<span>CurseForge</span>
                    </a>
                    <a class="btn btn-github" href="${project.links.github}" target="_blank" rel="noopener noreferrer">
                        ${ICONS.github}<span>GitHub</span>
                    </a>
                </div>
            </article>
        `
        )
        .join("");
}
loadProjects();
